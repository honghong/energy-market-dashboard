import { useEffect, useMemo, useState } from "react";
import {
  api,
  type Catalog,
  type IngestRun,
  type PriceHistory,
  type SpreadHistory,
  type Summary,
} from "./api";
import { KpiTile } from "./components/KpiTile";
import { PipelineRuns } from "./components/PipelineRuns";
import { PriceChart } from "./components/PriceChart";
import { SpreadPanel } from "./components/SpreadPanel";
import { formatDate, RANGES, rangeStart, type RangeKey } from "./format";

type Theme = "light" | "dark";

function initialTheme(): Theme | null {
  try {
    const saved = localStorage.getItem("theme");
    return saved === "light" || saved === "dark" ? saved : null;
  } catch {
    return null;
  }
}

export default function App() {
  const [catalog, setCatalog] = useState<Catalog | null>(null);
  const [summaries, setSummaries] = useState<Summary[]>([]);
  const [runs, setRuns] = useState<IngestRun[]>([]);
  const [seriesId, setSeriesId] = useState("wti");
  const [range, setRange] = useState<RangeKey>("1Y");
  const [spreadId, setSpreadId] = useState("crack_321");
  const [prices, setPrices] = useState<PriceHistory | null>(null);
  const [spread, setSpread] = useState<SpreadHistory | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const [theme, setTheme] = useState<Theme | null>(initialTheme);

  useEffect(() => {
    if (theme) document.documentElement.dataset.theme = theme;
  }, [theme]);

  function toggleTheme() {
    const current =
      theme ?? (matchMedia("(prefers-color-scheme: dark)").matches ? "dark" : "light");
    const next = current === "dark" ? "light" : "dark";
    setTheme(next);
    try {
      localStorage.setItem("theme", next);
    } catch {
      /* storage unavailable: theme still applies for this session */
    }
  }

  useEffect(() => {
    Promise.all([api.catalog(), api.summaries(), api.runs()])
      .then(([c, s, r]) => {
        setCatalog(c);
        setSummaries(s);
        setRuns(r);
      })
      .catch((e: Error) => setError(e.message));
  }, []);

  const latest = useMemo(() => {
    const dates = catalog?.series.map((s) => s.last_date).filter(Boolean) as string[] | undefined;
    return dates?.length ? dates.sort().at(-1) : undefined;
  }, [catalog]);
  const start = rangeStart(range, latest);

  useEffect(() => {
    if (!catalog) return;
    setLoading(true);
    api
      .prices(seriesId, start)
      .then(setPrices)
      .catch((e: Error) => setError(e.message))
      .finally(() => setLoading(false));
  }, [catalog, seriesId, start]);

  useEffect(() => {
    if (!catalog) return;
    api
      .spread(spreadId, start)
      .then(setSpread)
      .catch((e: Error) => setError(e.message));
  }, [catalog, spreadId, start]);

  const marketOf = (id: string) => catalog?.series.find((s) => s.id === id)?.market ?? "";
  const selectedName = catalog?.series.find((s) => s.id === seriesId)?.name ?? "";

  return (
    <div className="page">
      <header className="topbar">
        <div>
          <h1>Energy Market Dashboard</h1>
          <p className="topbar__sub">
            Crude, natural gas and refined-product prices with spread analytics
            {latest ? ` · data through ${formatDate(latest, "long")}` : ""}
          </p>
        </div>
        <div className="topbar__actions">
          {catalog && (
            <span className={`source source--${catalog.is_sample ? "sample" : "live"}`}>
              {catalog.is_sample
                ? "Sample data (simulated)"
                : catalog.data_source === "none"
                  ? "No data loaded yet"
                  : "Source: U.S. EIA"}
            </span>
          )}
          <button type="button" className="link-btn" onClick={toggleTheme}>
            Theme
          </button>
        </div>
      </header>

      {catalog?.is_sample && (
        <p className="notice" role="note">
          These prices are generated by the built-in simulator so the app runs without an API key.
          They are not market data. Set <code>EIA_API_KEY</code> and run the pipeline to load real
          EIA prices.
        </p>
      )}
      {error && (
        <p className="notice notice--error" role="alert">
          Could not reach the API: {error}
        </p>
      )}

      <div className="tiles">
        {summaries.map((s) => (
          <KpiTile
            key={s.series_id}
            summary={s}
            market={marketOf(s.series_id)}
            selected={s.series_id === seriesId}
            onSelect={setSeriesId}
          />
        ))}
      </div>

      <div className="filters" role="group" aria-label="Date range">
        <span className="filters__label">Range</span>
        <div className="segmented">
          {RANGES.map((r) => (
            <button
              key={r.key}
              type="button"
              aria-pressed={range === r.key}
              onClick={() => setRange(r.key)}
            >
              {r.label}
            </button>
          ))}
        </div>
      </div>

      <PriceChart title={selectedName} history={prices} loading={loading} />

      <div className="grid-2">
        {catalog && (
          <SpreadPanel
            spreads={catalog.spreads}
            selected={spreadId}
            onSelect={setSpreadId}
            history={spread}
          />
        )}
        <PipelineRuns runs={runs} />
      </div>

      <footer className="footer">
        Python · FastAPI · Pandas · SQLAlchemy · PostgreSQL · React · TypeScript · Recharts ·
        Docker
      </footer>
    </div>
  );
}
